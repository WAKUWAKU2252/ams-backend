// URL ของหน้าเว็บที่ backend ต้องประกอบเอง — นิยามที่เดียวของทั้งระบบ
//
// ทุกตัวในไฟล์นี้ "ออกไปข้างนอก" ทั้งหมด: ตัวหนึ่งถูกพิมพ์ลงสติกเกอร์ที่แปะบนตัวเครื่อง
// อีกตัวถูกฝังในอีเมลที่ส่งออกไปแล้วเรียกคืนไม่ได้ — เปลี่ยน path เมื่อไหร่ ของที่ออกไปแล้ว
// ทั้งหมดชี้ผิดที่ ถ้าหน้าเว็บย้ายที่ ให้ทำ redirect จาก path เดิมแทนการแก้ตรงนี้
//
// (APP_BASE_URL เปลี่ยนได้ถ้าโดเมนเปลี่ยน แต่สติกเกอร์ที่พิมพ์ไปแล้วก็ต้องพิมพ์ใหม่เหมือนกัน
//  — ตั้งให้เป็นโดเมนจริงตั้งแต่ก่อนพิมพ์ล็อตแรก อย่าปล่อยเป็น localhost)
// ═══════════════════════════════════════════════════════════════════════════
import { env } from '@config/env';

const base = () => env.APP_BASE_URL.replace(/\/+$/, '');

/**
 * URL ที่ฝังอยู่ใน QR ของชิ้นที่ออกเลขแล้ว — ชิ้นที่ยังไม่มีเลขไม่มี QR (ดู asset.qrCode)
 *
 * เก็บเป็น URL ไม่ใช่เลขเปล่า ๆ เพราะคนที่ต้องสแกนจริงคือคนที่เดินตรวจนับด้วยมือถือ
 * กล้องของ iOS/Android อ่าน URL แล้วเปิดหน้าให้ทันทีโดยไม่ต้องมีแอป ถ้าเก็บเป็นเลขเปล่า
 * กล้องจะขึ้นแค่ข้อความให้ก๊อป แล้วต้องเปิดแอปไปวางเองอีกที
 */
/**
 * ★ ต้องมีรหัสบริษัทใน URL (0021) — เลขสินทรัพย์ซ้ำกันข้ามบริษัทจริง 24 ตัว
 *
 * ไม่ใส่แล้วจะพังสองชั้นพร้อมกัน:
 *   1. qrCode ของสองชิ้นนั้นกลายเป็นสตริงเดียวกัน → uq_asset_qr_code ปฏิเสธ
 *      ตอน import ของ UBP เข้ามา (24 แถว insert ไม่ได้)
 *   2. ต่อให้ผ่าน DB มาได้ การสแกนก็ตอบไม่ได้ว่าหมายถึงชิ้นของบริษัทไหน
 *
 * บริษัทอยู่ใน path ไม่ใช่ query เพราะเป็นส่วนหนึ่งของ "ตัวตนของชิ้น" ไม่ใช่ตัวกรอง
 */
export function assetQrUrl(companyCode: string, assetNumber: string): string {
  return `${base()}/assets/${encodeURIComponent(companyCode)}/${encodeURIComponent(assetNumber)}`;
}

/**
 * ทางเข้าไปแก้ใบคำขอของผู้ขอ — ใส่ในอีเมลแจ้ง "มีรายการที่ต้องแก้"
 *
 * ต้องพาไปถึงใบเลย ไม่ใช่หน้ารายการ: ผู้ขอที่ได้เมลรู้อยู่แล้วว่าต้องแก้ใบไหน การให้ไปหา
 * เองในลิสต์คือขั้นตอนที่เพิ่มมาโดยไม่มีเหตุผล และใบที่ถูกตีกลับรายชิ้นยังเป็นสถานะ APPROVED
 * ซึ่งหาไม่เจอในตัวกรองปกติของหน้ารายการด้วย
 */
export function requestEditUrl(requestId: number): string {
  return `${base()}/create/${requestId}`;
}
