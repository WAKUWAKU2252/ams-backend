// รูปแบบเลขสินทรัพย์ของบริษัท — XXX-###-##-<ท่อนท้าย> เช่น COM-775-26-050
//
//   COM   สามอักษรที่คนใช้เรียกกลุ่มของ (ไม่ใช่หมวดบัญชี — ดู asset.assetClass)
//   775   รหัส cost center ตอนออกเลข (ชุดเก่าที่ยุบไปแล้วก็ยังอยู่ในเลขเดิม)
//   26    ปีที่ออกเลข
//   050   ท่อนท้าย: ตัวอักษร/ตัวเลขผสม ยาว 3–7 ตัว
//
// ⚠️ **regex นี้คือ "สคีมาที่บริษัทตั้งใจ" ไม่ใช่ "ทุกอย่างที่มีอยู่จริงใน SAP"**
// ใช้บังคับตอนคนกรอกเท่านั้น (assignAssetNumber) — ฝั่ง sync ห้ามเอาไปคัดของทิ้ง
// ของจริงที่ไม่เข้าสคีมามีอยู่ และเป็นของจริงทั้งนั้น เช่น
//   MAC-300-13-001.1  ชิ้นส่วนย่อยของ MAC-300-13-001 (มอเตอร์เกียร์ / ปั๊ม / ตู้ไฟฟ้า)
//   MAC-212-13-001/1  ถัง Silo — ใช้ทับแทนจุด
//   MAC-1-21/12-002   เครื่องบรรจุ — คนละสคีมาไปเลย
// พวกนี้ถูกดึงเข้าระบบตามปกติแล้วติดธงไว้ ไม่ได้ถูกปฏิเสธ (ดู isAssetNumber ข้างล่าง)
//
// ⚠️ ท่อนท้าย **ไม่ใช่ตัวเลข 3 หลักเสมอ** — แก้เมื่อ 2026-08-20 หลังวัดจาก OITM จริง
//
// ของเดิมบังคับ \d{3} ตายตัว ผลคือ **สินทรัพย์จริง 396 ชิ้นจาก 2,726 ไม่เคยถูก sync เข้ามาเลย**
// และเป็นของที่แพงที่สุดในบริษัท (อาคารโรงงาน APC 27 ล้าน, reactor tank 11 ล้าน) ทั้งยัง
// ทำให้บัญชีพิมพ์เลขพวกนั้นเข้า AMS ไม่ได้เพราะติด 422 ทรงที่วัดเจอจริงทั้งหมด:
//
//   COM-100-05-002      ท่อนท้าย 3 ตัว  (เลขล้วน — ทรงเดิมที่เคยรองรับอย่างเดียว)
//   FAB-200-14-B101     4 ตัว           (อักษรนำหน้าเลข)
//   COM-220-19-001BP    5 ตัว           (เลขตามด้วยอักษร)
//   LRD-110-17-001VTL   6 ตัว
//   LRD-110-17-0010VTL  7 ตัว           (ยาวสุดที่เจอ — เผื่อไว้เท่าที่วัดได้ ไม่เผื่อลอย ๆ)
//
// ⚠️ บทเรียนจากรอบนั้น: **ห้ามพิสูจน์ตัวกรองด้วยข้อมูลที่ผ่านตัวกรองนั้นมาแล้ว** ตอนแรกนับได้
// ว่า "ของใน SAP ที่เข้ารูปแบบ = 2,325 เท่ากับใน AMS เป๊ะ" แล้วสรุปว่าไม่มีอะไรตกหล่น ซึ่งผิด
// เพราะทั้งสองฝั่งกรองด้วยกติกาผิดตัวเดียวกัน ตัวเลขจึงยืนยันตัวเองได้เสมอ
// เวลาจะเช็คว่าเก็บครบไหม ต้องนับจากฐานทั้งหมด (OITM กลุ่ม 117) ไม่ใช่จากชุดที่กรองแล้ว
//
// ⚠️ ต้องอยู่ไฟล์เดียวเท่านั้น — สองรูปข้างล่างอธิบายกติกาเดียวกันคนละภาษา (regex สำหรับ
// validate ตอน Finance กรอก + ฝั่ง frontend / T-SQL สำหรับกรอง OITM) แก้ตัวใดตัวหนึ่งโดยไม่แก้
// อีกตัว = เลขที่ SAP ออกให้จริงจะกรอกเข้า AMS ไม่ได้ หรือของที่ sync มาจะติดชุดที่ไม่ควรติด
// ═══════════════════════════════════════════════════════════════════════════

/** ใช้ validate ค่าที่ Finance กรอก — anchored ทั้งสองด้าน ห้ามมีอะไรงอกหัวท้าย */
export const ASSET_NUMBER_REGEX = /^[A-Z]{3}-\d{3}-\d{2}-[A-Z0-9]{3,7}$/;

/** 'COM-100-05-002' = สั้นสุดที่เป็นไปได้ */
export const ASSET_NUMBER_MIN_LENGTH = 14;
/** 'LRD-110-17-0010VTL' = ยาวสุดที่วัดเจอใน OITM */
export const ASSET_NUMBER_MAX_LENGTH = 18;

/**
 * เลขนี้เข้าสคีมาของบริษัทไหม — ใช้ "ติดธง" ไม่ใช่ "คัดออก"
 *
 * ★ ไม่มีเวอร์ชัน T-SQL ของกติกานี้แล้วโดยตั้งใจ (เคยมี ถอดออก 2026-08-20)
 *
 * ตราบใดที่การตัดสินรูปแบบอยู่ใน WHERE ของ SQL ของที่ไม่เข้ากติกาจะ**หายเงียบ**เสมอ —
 * นั่นคือรากของบั๊กที่ทำให้สินทรัพย์ 396 ชิ้นไม่เคยเข้าระบบ และการไล่แก้ pattern ให้ครอบ
 * ความจริงที่ยังไม่เคยเห็นก็พลาดซ้ำอีกสองรอบ (เจอ `MAC-300-13-001.1` เลขชิ้นส่วนย่อยที่ใช้
 * จุด และ `MAC-212-13-001/1` ที่ใช้ทับ หลังจากคิดว่าครอบครบแล้ว)
 *
 * ตอนนี้ SQL จึงดึงมาทั้งกลุ่ม 117 (ยกเว้นรหัสตัวเลขล้วน) แล้วมาตัดสินที่ TypeScript ด้วย
 * regex ตัวเดียวข้างบน โดย **ของที่ไม่เข้าสคีมาก็ยังถูกดึงเข้าเป็นสินทรัพย์ตามปกติ** แค่ถูกนับ
 * และ log ไว้ให้ตามเก็บทีหลัง — ไม่มีอะไรหายอีก และไม่ต้องทำนายรูปแบบล่วงหน้าอีกต่อไป
 *
 * ถังตกค้างไม่ต้องมีตารางแยก เพราะของถูกเก็บใน asset อยู่แล้ว ถามเมื่อไหร่ก็ได้ด้วย:
 *   SELECT "assetNumber", description FROM asset
 *   WHERE origin = 'SAP_LEGACY' AND "deletedAt" IS NULL
 *     AND "assetNumber" !~ '^[A-Z]{3}-[0-9]{3}-[0-9]{2}-[A-Z0-9]{3,7}$';
 */
export const isAssetNumber = (code: string | null | undefined): boolean =>
  typeof code === 'string' && ASSET_NUMBER_REGEX.test(code);

/**
 * รหัสจัดซื้อ = **ตัวเลขล้วน** (เช่น '5320107') ไม่ใช่ "อะไรก็ตามที่ไม่ใช่เลขสินทรัพย์"
 *
 * นิยามเดิมเป็นแบบหลังแล้วพัง: มันเหมารวมสินทรัพย์ 396 ชิ้นที่ท่อนท้ายไม่เข้ารูปแบบเก่า
 * ไปเป็น "รหัสจัดซื้อ" ด้วย ซึ่งจะทำให้อาคารโรงงาน 27 ล้านถูกใช้เป็นตารางค้นหาหมวดสินค้า
 * ในกลุ่ม 117 มีตัวเลขล้วนอยู่แค่ 5 ตัว (วัด 2026-08-20)
 */
export const purchasingCodeSqlFilter = (col: string): string => `${col} NOT LIKE '%[^0-9]%'`;
