// กติกาว่า "อะไรถือเป็นสินทรัพย์" — ใช้ร่วมกันหลาย module (asset, purchase-order,
// asset-request) จึงอยู่ที่ common ไม่ใช่ในโมดูลใดโมดูลหนึ่ง
// ถ้าปล่อยให้แต่ละที่ถือเลขของตัวเอง วันที่บัญชีเปลี่ยนเกณฑ์จะแก้ไม่ครบแล้วสองหน้าจอ
// ให้คำตอบต่างกันโดยไม่มีใครรู้

/**
 * เพดานล่างของราคา "ต่อชิ้น" ที่ถือเป็นสินทรัพย์ — ต่ำกว่าหรือเท่านี้ลงบัญชีเป็นค่าใช้จ่าย
 * ไม่ต้องขึ้นทะเบียนติดตาม (ของถูกมูลค่าน้อย ต้นทุนติดตามแพงกว่าตัวของ)
 *
 * ★ ต่อชิ้น ไม่ใช่ยอดรวมบรรทัด — คีย์บอร์ด 3,200 x 10 ตัว = 32,000 บาท ก็ยังไม่ใช่สินทรัพย์
 *
 * TODO: ย้ายไปเป็นค่าตั้งค่าระบบเมื่อมีตาราง config — ตอนนี้บัญชีเปลี่ยนเกณฑ์ต้องแก้โค้ด
 */
export const ASSET_MIN_UNIT_PRICE = 5000;

/** บรรทัดนี้ต้องขึ้นทะเบียนเป็นสินทรัพย์ไหม (ตัดสินที่ราคาต่อชิ้น) */
export function isRegistrable(unitPrice: number): boolean {
  return unitPrice > ASSET_MIN_UNIT_PRICE;
}
